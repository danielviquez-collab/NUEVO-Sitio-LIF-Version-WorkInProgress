import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
export function cleanPngMetadata(input) {
  assert.ok(input.subarray(0, 8).equals(signature), 'PNG invalido');
  const kept = [signature], pixels = [], removed = [];
  let offset = 8;
  while (offset < input.length) {
    assert.ok(offset + 12 <= input.length, 'PNG truncado');
    const length = input.readUInt32BE(offset), end = offset + length + 12;
    assert.ok(end <= input.length, 'Chunk truncado');
    const type = input.toString('ascii', offset + 4, offset + 8);
    const data = input.subarray(offset + 8, end - 4);
    const privateAttribution = ['caBX', 'iTXt', 'tEXt', 'zTXt', 'eXIf'].includes(type) &&
      /openai|chatgpt|codex-preview|generated by/i.test(data.toString('latin1'));
    if (privateAttribution) removed.push(type);
    else kept.push(input.subarray(offset, end));
    if (type === 'IDAT') pixels.push(data);
    offset = end;
  }
  const output = Buffer.concat(kept);
  assert.ok(output.subarray(output.length - 8, output.length - 4).toString('ascii') === 'IEND');
  return { output, removed, pixelSha256: createHash('sha256').update(Buffer.concat(pixels)).digest('hex') };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const path of process.argv.slice(2)) {
    const result = cleanPngMetadata(await readFile(path));
    if (result.removed.length) await writeFile(path, result.output);
    assert.equal(cleanPngMetadata(result.output).pixelSha256, result.pixelSha256);
    console.log(JSON.stringify({ file: path, removed: result.removed, pixelsUnchanged: true }));
  }
}
