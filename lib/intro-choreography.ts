type MotionKey = 'x' | 'y' | 'rotation' | 'sx' | 'sy' | 'opacity';
const value = (frame: IntroFrame, key: MotionKey) =>
  frame[key] ?? (['sx', 'sy', 'opacity'].includes(key) ? 1 : 0);
function tangent(track: Track, i: number, key: MotionKey) {
  const slope = (a: number, b: number) =>
    (value(track[b], key) - value(track[a], key)) / (track[b].at - track[a].at);
  if (i === 0 || i === track.length - 1) return 0;
  const before = slope(i - 1, i),
    after = slope(i, i + 1);
  if (before * after <= 0) return 0;
  const h1 = track[i].at - track[i - 1].at,
    h2 = track[i + 1].at - track[i].at;
  const w1 = 2 * h2 + h1,
    w2 = h2 + 2 * h1;
  return (w1 + w2) / (w1 / before + w2 / after);
}
export function sampleIntroTrack(track: Track, timeMs: number) {
  const next = track.findIndex((point) => point.at > timeMs);
  const i = next < 0 ? track.length - 1 : Math.max(0, next - 1),
    a = track[i],
    b = track[next < 0 ? i : next];
  const duration = b.at - a.at,
    t = duration ? Math.max(0, Math.min(1, (timeMs - a.at) / duration)) : 0;
  const sample = (key: MotionKey) =>
    a === b
      ? value(a, key)
      : (2 * t ** 3 - 3 * t ** 2 + 1) * value(a, key) +
        (t ** 3 - 2 * t ** 2 + t) * duration * tangent(track, i, key) +
        (-2 * t ** 3 + 3 * t ** 2) * value(b, key) +
        (t ** 3 - t ** 2) * duration * tangent(track, i + 1, key);
  return {
    x: sample('x'),
    y: sample('y'),
    rotation: sample('rotation'),
    sx: sample('sx'),
    sy: sample('sy'),
    opacity: sample('opacity'),
  };
}
export function completeIntroPose(proposal: IntroProposal, timeMs: number) {
  const tracks = choreography[proposal.id],
    t = Math.max(0, Math.min(proposal.durationMs, timeMs));
  const dot = {
    ...sampleIntroTrack(proposal.frames, t),
    opacity: Math.min(1, t / 80),
  };
  return {
    ensemble: sampleIntroTrack(tracks.ensemble, t),
    parts: {
      leaf: sampleIntroTrack(tracks.leaf, t),
      letterL: sampleIntroTrack(tracks.letterL, t),
      letterI: sampleIntroTrack(tracks.letterI, t),
      letterF: sampleIntroTrack(tracks.letterF, t),
      dot,
      laica: sampleIntroTrack(tracks.laica, t),
    },
  };
}
