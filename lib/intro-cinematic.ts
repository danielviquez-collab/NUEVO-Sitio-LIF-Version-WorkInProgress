const smooth = (a: number, b: number, time: number) => {
  const t = Math.max(0, Math.min(1, (time - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

export function cinematicIntroPose(proposal: IntroProposal, timeMs: number) {
  const spec = direction[proposal.id];
  const t = Math.max(0, Math.min(proposal.durationMs, timeMs));
  const parts = Object.fromEntries(
    INTRO_PARTS.map((part) => [part, sampleIntroTrack(spec.tracks[part], t)]),
  ) as Record<IntroPart, ReturnType<typeof sampleIntroTrack>>;
  const material = Object.fromEntries(
    Object.entries(spec.reveal).map(([part, r]) => {
      const progress = smooth(r.start, r.end, t);
      return [
        part,
        {
          x: r.x,
          y: r.y,
          radius: 1200 * progress,
          ink: progress,
          fill: smooth(0.15, 0.88, progress),
          outline:
            progress === 0 || progress === 1 ? 0 : Math.sin(progress * Math.PI),
        },
      ];
    }),
  ) as Record<
    Exclude<IntroPart, 'dot'>,
    {
      x: number;
      y: number;
      radius: number;
      ink: number;
      fill: number;
      outline: number;
    }
  >;
  // The short ribbon is sampled from the same audible-clock trajectory as the point.
  const trail = Array.from({ length: 12 }, (_, i) => {
    const p = sampleIntroTrack(spec.tracks.dot, Math.max(0, t - (11 - i) * 11));
    return { x: 502.188 + p.x, y: 449.632 + p.y };
  });
  return {
    ensemble: sampleIntroTrack(spec.tracks.ensemble, t),
    parts,
    material,
    trail,
    trailOpacity:
      0.35 *
      smooth(0, 120, t) *
      (1 - smooth(spec.trailUntil - 160, spec.trailUntil, t)),
  };
}

export function cinematicAccentTimes(proposal: IntroProposal) {
  return direction[proposal.id].tracks.dot
    .map((frame) => frame.at)
    .filter((at) => proposal.cues.includes(at));
}
